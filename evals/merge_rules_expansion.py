"""
Merge the reviewed card-free expansion rows (q100-q155) into the existing
validated eval set (q001-q032) to produce evals/questions_rules86.jsonl.

Pure file work: no API calls, no model calls, no embeddings.

Applies Jon's already-made review decisions:
  1. Drop q148 (no CR rule resolves the race; both drafter and reviewer agree).
  2. Upgrade q147 to high confidence with a rewritten question/answer, backed
     by the CR 800.4d worked example (Astral Slide / Hypnotic Specter).
  3. Fix q129's overstatement about "marked damage" being copied-and-excluded
     when it was never a copiable value in the first place (add 120.3e).
  4. Add governing rules the draft omitted to q109, q110, q152, q155's gold
     lists, each with a verbatim cr_quotes entry.

Idempotent: reads the two input files fresh and writes the output fresh
every run.
"""
import json
import sys

REPO_ROOT = r"D:\Job_hunt\mtg-rules-bot"
EXISTING_PATH = f"{REPO_ROOT}/evals/questions_rules31.jsonl"
DRAFT_PATH = f"{REPO_ROOT}/evals/_rules_expansion_draft.jsonl"
OUTPUT_PATH = f"{REPO_ROOT}/evals/questions_rules86.jsonl"
CR_PATH = f"{REPO_ROOT}/data/raw/MagicCompRules 20260619.txt"

DROP_IDS = {"q148"}

# Verbatim CR quotes for every rule number this script adds to a row's gold
# list. Located directly in the CR file (line numbers noted in the report).
CR_QUOTES_TO_ADD = {
    "800.4d": (
        "800.4d If an object that would be owned by a player who has left "
        "the game would be created in any zone, it isn\u2019t created. If a "
        "triggered ability that would be controlled by a player who has "
        "left the game would be put onto the stack, it isn\u2019t put on "
        "the stack.\nExample: Astral Slide is an enchantment that reads, "
        "\u201cWhenever a player cycles a card, you may exile target "
        "creature. If you do, return that creature to the battlefield "
        "under its owner\u2019s control at the beginning of the next end "
        "step.\u201d During Alex\u2019s turn, Bianca uses Astral Slide\u2019s "
        "ability to exile Alex\u2019s Hypnotic Specter. Before the end of "
        "that turn, Bianca leaves the game. At the beginning of the end "
        "step, the delayed triggered ability generated by Astral Slide "
        "that would return Hypnotic Specter to the battlefield triggers, "
        "but it isn\u2019t put on the stack. Hypnotic Specter never returns "
        "to the battlefield."
    ),
    "120.3e": (
        "120.3e Damage dealt to a creature by a source with neither wither "
        "nor infect causes that much damage to be marked on that creature."
    ),
    "800.7": (
        "800.7. In a multiplayer game other than a Two-Headed Giant game, "
        "the starting player doesn\u2019t skip the draw step of their first "
        "turn. In a Two-Headed Giant game, the team who plays first skips "
        "the draw step of their first turn. See rule 103.8."
    ),
    "810.6": (
        "810.6. The team who plays first skips the draw step of its first "
        "turn."
    ),
    "405.5": (
        "405.5. When all players pass in succession, the top (last-added) "
        "spell or ability on the stack resolves. If the stack is empty "
        "when all players pass, the current step or phase ends and the "
        "next begins."
    ),
    "403.4": (
        "403.4. Whenever a permanent enters the battlefield, it becomes a "
        "new object and has no relationship to any previous permanent "
        "represented by the same card, except for the cases listed in rule "
        "400.7. (This is also true for any objects entering any zone.)"
    ),
}


def load_jsonl(path):
    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


def verify_cr_quotes_present():
    """Belt-and-suspenders: confirm every quote we're about to add is
    actually present verbatim in the CR file, so we never ship an invented
    quote."""
    with open(CR_PATH, "r", encoding="utf-8") as f:
        cr_text = f.read()
    missing = []
    for rule_num, quote in CR_QUOTES_TO_ADD.items():
        # Compare on the first line of multi-line quotes (the example text
        # in 800.4d spans a following "Example:" line already captured
        # verbatim above); just check the quote's core sentence is present.
        first_line = quote.split("\n")[0]
        if first_line not in cr_text:
            missing.append(rule_num)
    if missing:
        print(f"STOP: could not verify these rule numbers in the CR file: {missing}")
        sys.exit(1)


def main():
    verify_cr_quotes_present()

    existing_rows = load_jsonl(EXISTING_PATH)
    draft_rows = load_jsonl(DRAFT_PATH)

    by_id = {r["id"]: r for r in draft_rows}

    dropped = []
    kept_draft_rows = []
    for row in draft_rows:
        if row["id"] in DROP_IDS:
            dropped.append(row["id"])
            continue
        kept_draft_rows.append(row)

    # --- Edit q147: upgrade -------------------------------------------------
    q147 = by_id["q147"]
    if "800.4d" not in q147["gold"]:
        q147["gold"] = q147["gold"] + ["800.4d"]
    q147["confidence"] = "high"
    q147["question"] = (
        "If a player leaves a multiplayer game while controlling a "
        "permanent that has a leaves-the-battlefield triggered ability, "
        "does that ability trigger, and does it go on the stack?"
    )
    q147["answer_gold"] = (
        "It triggers, but it isn't put on the stack. The player's "
        "departure moves their permanents out of the game, so the trigger "
        "condition is met -- but a triggered ability that would be "
        "controlled by a player who has left the game is never put onto "
        "the stack, so its effect simply never happens. The rules use "
        "exactly that split: the ability triggers, and it isn't put on the "
        "stack."
    )
    q147.setdefault("cr_quotes", {})["800.4d"] = CR_QUOTES_TO_ADD["800.4d"]
    # This row no longer rests on an unresolved inference; drop the stale
    # low-confidence flag left over from the draft review.
    q147.pop("question_flag", None)

    # --- Edit q129: fix overstatement ---------------------------------------
    q129 = by_id["q129"]
    if "120.3e" not in q129["gold"]:
        q129["gold"] = q129["gold"] + ["120.3e"]
    old_phrase = (
        "Counters, marked damage, stickers, and other continuous effects "
        "presently affecting the original are explicitly not copied."
    )
    new_phrase = (
        "Status, counters and stickers are explicitly excluded from what "
        "gets copied. Marked damage isn't copied either, but for a "
        "different reason -- damage is merely marked on a permanent, so it "
        "was never one of the copiable values in the first place."
    )
    if old_phrase not in q129["answer_gold"]:
        print("STOP: expected phrase not found verbatim in q129 answer_gold")
        sys.exit(1)
    q129["answer_gold"] = q129["answer_gold"].replace(old_phrase, new_phrase)
    q129.setdefault("cr_quotes", {})["120.3e"] = CR_QUOTES_TO_ADD["120.3e"]

    # --- Gold completeness additions ----------------------------------------
    additions = {
        "q109": "800.7",
        "q110": "810.6",
        "q152": "405.5",
        "q155": "403.4",
    }
    for qid, rule_num in additions.items():
        row = by_id[qid]
        if rule_num not in row["gold"]:
            row["gold"] = row["gold"] + [rule_num]
        row.setdefault("cr_quotes", {})[rule_num] = CR_QUOTES_TO_ADD[rule_num]

    # q155 keeps confidence "medium" per Jon's instructions -- no change.

    merged_rows = existing_rows + kept_draft_rows

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        for row in merged_rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    # --- Validation ----------------------------------------------------------
    problems = []

    if len(merged_rows) != 86:
        problems.append(f"row count {len(merged_rows)} != 86")

    ids_seen = set()
    for row in merged_rows:
        if row["id"] in ids_seen:
            problems.append(f"duplicate id {row['id']}")
        ids_seen.add(row["id"])
        for field in ("question", "answer_gold"):
            if not row.get(field):
                problems.append(f"{row['id']} missing/empty {field}")
        if not row.get("gold"):
            problems.append(f"{row['id']} missing/empty gold")
        # The 31 pre-existing rows use an older schema (gold_mined_original /
        # gold_validated_by) with no cr_quotes field at all -- that's their
        # native format and out of scope (task says don't modify that file).
        # The cr_quotes-completeness check applies to the draft-derived rows,
        # which do carry cr_quotes.
        if "cr_quotes" in row:
            cr_quotes = row["cr_quotes"]
            for rule_num in row.get("gold", []):
                if rule_num not in cr_quotes:
                    problems.append(f"{row['id']} gold rule {rule_num} missing from cr_quotes")

    # Re-parse the written file line by line to confirm valid JSON per line.
    with open(OUTPUT_PATH, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                json.loads(line)
            except json.JSONDecodeError as e:
                problems.append(f"line {i} invalid JSON: {e}")

    print(f"COUNTS | in(existing={len(existing_rows)}, draft={len(draft_rows)}) "
          f"dropped={dropped} out={len(merged_rows)}")
    if problems:
        print("VALIDATION FAILED:")
        for p in problems:
            print(f"  - {p}")
        sys.exit(1)
    else:
        print("VALIDATION PASSED: 86 rows, no dup ids, all fields present, "
              "all gold rules have cr_quotes, all lines valid JSON")


if __name__ == "__main__":
    main()
