"""Harvest Jon's grading-note free text into a categorized improvement backlog.

Jon's grading `note` fields are largely SYSTEM-IMPROVEMENT feedback, not just
verdict rationale (his call, 2026-07-23). This tool reads every verdict/export
file, dedupes notes, sorts them into actionable buckets, and writes
docs/grading-feedback-backlog.md. Re-run after EACH grading export so nothing
dies in verdict JSON.

Sources: evals/verdicts_*.json (committed, model lab) + the browser exports in
the user's Downloads (answer_verdicts*.json). The v3ab grading export lands
there too once saved.

Read-only on the verdict data; writes only the backlog doc. No API calls.
Run:  PYTHONIOENCODING=utf-8 .venv/Scripts/python.exe evals/harvest_grading_notes.py
"""
from __future__ import annotations
import json, glob, os, re, collections, pathlib

REPO = pathlib.Path(__file__).resolve().parents[1]
BACKLOG = REPO / "docs" / "grading-feedback-backlog.md"
DOWNLOADS = pathlib.Path(os.path.expanduser("~")) / "Downloads"

# Category order matters: a note is filed under the FIRST matching category so
# each note appears once. Order = most-specific first; prompt-tuning is the LAST
# actionable bucket (its wording patterns are broad, so a note that is really a
# retrieval gap or a display bug should be claimed by those first). Notes that
# are ONLY about answer wording/structure still land in prompt-tuning -- the
# prompt-v4 feed -- rather than falling through to rationale.
CATEGORIES = [
    ("retrieval-gap", re.compile(
        r"\b(should (also )?(be )?(surfac|add|includ|retriev)|not (surfaced|retrieved|in pool)"
        r"|gold.*(missing|not)|needs to be added|rank(ed|s)? \d+|ranks? \d+|query rewrit"
        r"|not retrieved|didn'?t (get|retrieve))\b", re.I)),
    ("feature-escalate", re.compile(
        r"\b(escalat|ask (a |the )?(real|human|judge)|round of clarifying|clarifying question)\b", re.I)),
    ("display-ui", re.compile(
        r"\b(missing (scryfall|cr|ruling|rule).*text|text (is )?missing"
        r"|citations are (there|present)|double bracket|not (shown|displayed|rendered))\b", re.I)),
    ("data-bug", re.compile(
        r"\b(wrong card|stale|malformed|blank|empty (answer|text)|cut off|truncat"
        r"|contradicts? itself|self.contradict)\b", re.I)),
    ("prompt-tuning", re.compile(
        r"\b(should (always|never|open|lead|start|state|say|answer|define|address)"
        r"|buried|bury|buries|leads with|too much|focus(ing|es)? (too )?much"
        r"|direct answer|the answer is|restat|verbose|hedg|assum(e|ing|ption)"
        r"|full name|role word|the attacker|the blocker|multiplayer|two.player"
        r"|card text override|mana symbol|priorit(y|ise)|weird way to word"
        r"|system prompt|instruction)\b", re.I)),
]


def _rows(d):
    if isinstance(d, list):
        return d
    for k in ("verdicts", "rows", "answers", "results"):
        if isinstance(d.get(k), list):
            return d[k]
    return list(d.values()) if isinstance(d, dict) else []


def main() -> None:
    sources = sorted(glob.glob(str(REPO / "evals" / "verdicts_*.json")))
    sources += sorted(glob.glob(str(DOWNLOADS / "answer_verdicts*.json")))

    buckets: dict[str, list] = collections.defaultdict(list)
    rationale = []
    seen: set = set()
    total = 0
    for f in sources:
        try:
            d = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        for r in _rows(d):
            if not isinstance(r, dict):
                continue
            note = str(r.get("note", "")).strip()
            if not note:
                continue
            qid = r.get("id")
            key = (qid, note[:60])
            if key in seen:
                continue
            seen.add(key)
            total += 1
            for cat, rx in CATEGORIES:
                if rx.search(note):
                    buckets[cat].append((qid, note))
                    break
            else:
                rationale.append((qid, note))

    labels = {
        "prompt-tuning": "System-prompt improvement ideas (the prompt-v4 / v-next feed)",
        "retrieval-gap": "Retrieval / gold gaps (a rule that should be surfaced isn't)",
        "display-ui": "Grading-UI display bugs (rule/ruling TEXT not shown though citations present)",
        "data-bug": "Data / formatting / answer-shape bugs",
        "feature-escalate": "Feature: clarify-then-escalate signals",
    }
    out = [
        "# Grading-feedback backlog (harvested from verdict note fields)",
        "",
        "Auto-generated by `evals/harvest_grading_notes.py`. Jon's grading notes are "
        "largely SYSTEM-IMPROVEMENT feedback, not verdict rationale. **Re-run after every "
        "grading export** (the tool reads evals/verdicts_*.json + ~/Downloads/answer_verdicts*.json). "
        "`rules-rationale` notes are left with the verdicts, not listed here.",
        "",
        f"_Harvested {total} unique notes; {sum(len(v) for v in buckets.values())} actionable, "
        f"{len(rationale)} verdict-rationale (not shown)._",
    ]
    for cat, _ in CATEGORIES:
        items = buckets.get(cat, [])
        out.append(f"\n## {labels[cat]} ({len(items)})\n")
        if not items:
            out.append("_(none yet)_")
        for qid, note in items:
            out.append(f"- **{qid}**: {note[:320]}")
    BACKLOG.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"harvested {total} notes -> {BACKLOG}")
    for cat, _ in CATEGORIES:
        print(f"  {cat:18} {len(buckets.get(cat, []))}")
    print(f"  {'rules-rationale':18} {len(rationale)}")


if __name__ == "__main__":
    main()
